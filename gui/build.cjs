#!/usr/bin/env node
/**
 * gui/build.cjs — one-time build step for the avatar renderer.
 *
 * Reads avatar-studio-project.json (10 avatar designs, shared expressions +
 * sequences pulled from smontlouis/bible-strong-avatar-lab), bakes a
 * per-avatar behavior block onto every avatar (eye geometry rebaselined per
 * avatar, matching what the studio's own export step does), and emits one
 * self-contained ES module per avatar under gui/engine/avatars/ that wraps
 * the studio's real rendering engine (gui/engine/avatar-engine.js) and
 * runtime (gui/engine/avatar-runtime.js).
 *
 * Run again any time avatar-studio-project.json changes:
 *   node gui/build.cjs
 */
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const PROJECT_PATH = path.join(ROOT, '..', 'avatar-studio-project.json');
const ENGINE_JS = fs.readFileSync(path.join(ROOT, 'engine', 'avatar-engine.js'), 'utf8');
const RUNTIME_JS = fs.readFileSync(path.join(ROOT, 'engine', 'avatar-runtime.js'), 'utf8');

// ── constants ported from src/features/avatar/avatars.ts ────────────────────
const defaultAvatarEyes = {
  widthLeft: 20,
  widthRight: 20,
  heightLeft: 50,
  heightRight: 50,
  spacing: 35,
  positionXLeft: 0,
  positionXRight: 0,
  positionYLeft: -7,
  positionYRight: -7,
  leftAngle: 0,
  rightAngle: 0,
};
const eyeDefaultFields = Object.keys(defaultAvatarEyes);

function applyAvatarEyeDefaults(expression, eyes) {
  const result = { ...expression };
  eyeDefaultFields.forEach(field => {
    result[field] = expression[field] + eyes[field] - defaultAvatarEyes[field];
  });
  result.widthLeft = Math.max(10, result.widthLeft);
  result.widthRight = Math.max(10, result.widthRight);
  result.heightLeft = Math.max(10, result.heightLeft);
  result.heightRight = Math.max(10, result.heightRight);
  return result;
}

function slugify(value) {
  return (
    value
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || 'animation'
  );
}

function animationKey(sequence, used) {
  const base = slugify(sequence.builtIn ? sequence.id : sequence.name);
  let key = base;
  let suffix = 2;
  while (used.has(key)) key = `${base}-${suffix++}`;
  used.add(key);
  return key;
}

// ── load source data ─────────────────────────────────────────────────────────
const project = JSON.parse(fs.readFileSync(PROJECT_PATH, 'utf8'));
const sharedExpressions = project.expressions;
const sharedSequences = project.sequences;

const manifest = [];

for (const avatar of project.library.avatars) {
  // 1. Bake a full behavior block (per-avatar eye-adjusted expressions +
  //    the full shared sequence library) onto every avatar, matching the
  //    AvatarBehaviorLibrary shape the studio already used for Cubee.
  const bakedExpressions = sharedExpressions.map(expression =>
    applyAvatarEyeDefaults(expression, avatar.eyes)
  );
  avatar.behavior = {
    expressions: bakedExpressions,
    sequences: sharedSequences,
  };

  // 2. Build the AvatarExportPayload the studio's own exporter produces,
  //    referencing only the expressions actually used by each sequence.
  const expressionById = new Map(bakedExpressions.map(e => [e.id, e]));
  const usedKeys = new Set();
  const referencedIds = new Set(
    sharedSequences.flatMap(seq => seq.steps.map(step => step.expressionId))
  );
  const exportedExpressions = {};
  referencedIds.forEach(id => {
    const expr = expressionById.get(id);
    if (!expr) return;
    const { semanticKey, ...legacy } = expr;
    exportedExpressions[id] = legacy;
  });
  const animations = {};
  sharedSequences.forEach(seq => {
    const key = animationKey(seq, usedKeys);
    animations[key] = {
      name: seq.name,
      description: seq.description,
      playbackMode: seq.playbackMode,
      blink: { ...seq.blink },
      steps: seq.steps
        .filter(step => exportedExpressions[step.expressionId])
        .map(({ expressionId, holdMs, transitionMs, transition }) => ({
          expressionId,
          holdMs,
          transitionMs,
          transition,
        })),
    };
  });

  const payload = {
    version: 1,
    avatar: {
      name: avatar.name,
      surface: avatar.body.primary,
      bodyNodes: avatar.body.nodes,
      colors: avatar.colors,
      renderStyle: avatar.renderStyle,
    },
    expressions: exportedExpressions,
    animations,
  };

  // 3. Emit one thin ES module per avatar that imports the shared engine.
  //    The engine + runtime used to be inlined into every avatar (~37KB each,
  //    x10), so any screen showing several avatars parsed the same minified
  //    engine repeatedly.
  const slug = slugify(avatar.name || avatar.id);
  const moduleSource = `// Generated by gui/build.cjs — do not edit by hand.
import { createAvatarFactory } from '../avatar-shared.js';
const DATA = ${JSON.stringify(payload)};
const mountAvatar = createAvatarFactory(DATA);
export const availableAnimations = Object.freeze(Object.keys(DATA.animations));
export const avatarMeta = Object.freeze(${JSON.stringify({
    id: avatar.id,
    slug,
    name: avatar.name,
    colors: avatar.colors,
  })});
export function createAvatar(target, options = {}) { return mountAvatar(target, options); }
export default createAvatar;
`;
  fs.writeFileSync(path.join(ROOT, 'engine', 'avatars', `${slug}.avatar.js`), moduleSource);

  manifest.push({
    id: avatar.id,
    slug,
    name: avatar.name,
    colors: avatar.colors,
    module: `engine/avatars/${slug}.avatar.js`,
    animations: Object.keys(animations),
    defaultAnimation: Object.keys(animations)[0] || null,
  });
}

// The runtime closes over `DATA` and `AvatarProceduralEngine` as free
// variables, so it cannot simply be exported — it is wrapped in a factory that
// takes DATA as a parameter. `mountAvatar` is a hoisted function declaration
// inside RUNTIME_JS, so returning it works wherever it sits in that source.
// Moving the runtime into a nested scope can only shadow, never collide: both
// halves already shared one module scope, so any top-level collision would
// already have been a SyntaxError.
const sharedSource = `// Generated by gui/build.cjs — do not edit by hand.
${ENGINE_JS}
export function createAvatarFactory(DATA) {
${RUNTIME_JS}
  return mountAvatar;
}
`;
fs.writeFileSync(path.join(ROOT, 'engine', 'avatar-shared.js'), sharedSource);

fs.writeFileSync(path.join(ROOT, 'data', 'manifest.json'), JSON.stringify(manifest, null, 2));
fs.writeFileSync(PROJECT_PATH, JSON.stringify(project, null, 2));

console.log(`Built ${manifest.length} avatar modules → gui/engine/avatars/`);
console.log(`Wrote gui/data/manifest.json`);
console.log(`Attached behavior blocks to all ${project.library.avatars.length} avatars in avatar-studio-project.json`);
